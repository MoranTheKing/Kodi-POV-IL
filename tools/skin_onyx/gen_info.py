# -*- coding: utf-8 -*-
"""Generate the video information screen (DialogVideoInfo.xml) of skin.povil.onyx.

    python gen_info.py ../../skin.povil.onyx

Right to left: the Hebrew logo or title, details, plot and credits in a
column on the right, the poster (or the episode still) on the left, the
buttons along the bottom with Play first on the right. Kodi swaps the plot
(control 4) for the cast list (50) with its button 5; the cast list is a
right-aligned column in the plot's place.
"""
import os
import sys
from xml.sax.saxutils import escape

import gen_home as H

NL = chr(10)
MIN = " דק'"
RIGHT = 1920 - H.MARGIN
COL = 1000          # width of the text column
IS_EP = 'String.IsEqual(ListItem.DBType,episode)'


def e(s):
    return escape(s)


def button(x, d, bid, label, vis='', primary=False, extra=''):
    x(d, '<control type="button" id="%d">' % bid)
    x(d + 1, '<width min="190">auto</width><height>60</height><textoffsetx>34</textoffsetx>')
    x(d + 1, '<font>povil_row</font><align>center</align><aligny>center</aligny>')
    x(d + 1, '<textcolor>povil_white</textcolor><focusedcolor>povil_ink</focusedcolor>')
    x(d + 1, '<texturenofocus border="24" colordiffuse="%s">povil/pill48.png</texturenofocus>' % ('40D9B77E' if primary else '24FFFFFF'))
    x(d + 1, '<texturefocus border="24" colordiffuse="povil_gold">povil/pill48.png</texturefocus>')
    if label:
        x(d + 1, '<label>%s</label>' % e(label))
    if extra:
        x(d + 1, extra)
    if vis:
        x(d + 1, '<visible>%s</visible>' % e(vis))
    x(d, '</control>')


def gen():
    x = H.X()
    x(0, '<?xml version="1.0" encoding="UTF-8"?>')
    x(0, '<!-- Generated by tools/skin_onyx/gen_info.py. Do not edit by hand. -->')
    x(0, '<window>')
    x(1, '<defaultcontrol always="true">8</defaultcontrol>')
    x(1, '<controls>')
    x(2, '<control type="group">')
    x(3, '<animation type="WindowOpen"><effect type="fade" start="0" end="100" time="260" /></animation>')
    x(3, '<animation type="WindowClose"><effect type="fade" start="100" end="0" time="200" /></animation>')
    # Backdrop
    x(3, '<control type="image"><left>0</left><top>0</top><width>1920</width><height>1080</height><texture>povil/ambient.jpg</texture></control>')
    x(3, '<control type="image"><left>0</left><top>0</top><width>1920</width><height>1080</height>'
         '<texture background="true">$INFO[ListItem.Art(fanart)]</texture><aspectratio>scale</aspectratio><fadetime>300</fadetime></control>')
    for left, top, w, h, tex, diffuse in ((0, 0, 1920, 1080, 'white', 'A0000000'), (420, 0, 1500, 1080, 'grad_right', ''),
                                          (0, 380, 1920, 700, 'grad_bottom', ''), (0, 0, 1920, 1080, 'vignette', '')):
        x(3, '<control type="image"><left>%d</left><top>%d</top><width>%d</width><height>%d</height>'
             '<texture%s>povil/%s.png</texture></control>' % (left, top, w, h, (' colordiffuse="%s"' % diffuse) if diffuse else '', tex))
    # Poster (or episode still), left
    for kind, vis, (left, top, w, h), art, mask in (
            ('poster', '!' + IS_EP, (130, 150, 400, 600), 'ListItem.Art(poster)', 'mask_poster'),
            ('still', IS_EP, (110, 230, 560, 315), 'ListItem.Art(thumb)', 'mask_landscape')):
        x(3, '<control type="group"><left>%d</left><top>%d</top><visible>%s</visible>' % (left, top, vis))
        x(4, '<control type="image"><left>-34</left><top>-26</top><width>%d</width><height>%d</height><texture border="54">povil/shadow.png</texture></control>' % (w + 68, h + 68))
        x(4, '<control type="image"><left>0</left><top>0</top><width>%d</width><height>%d</height><texture border="30" colordiffuse="1FFFFFFF">povil/rounded_fill.png</texture></control>' % (w, h))
        x(4, '<control type="image"><left>0</left><top>0</top><width>%d</width><height>%d</height>'
             '<texture background="true" diffuse="povil/%s.png">$INFO[%s]</texture><aspectratio scalediffuse="false">scale</aspectratio></control>' % (w, h, mask, art))
        x(3, '</control>')
    # Text column, right
    left = RIGHT - COL
    x(3, '<control type="image"><left>%d</left><top>96</top><width>640</width><height>190</height>'
         '<texture background="true">$INFO[ListItem.Art(povil_logo)]</texture><aspectratio align="right" aligny="bottom">keep</aspectratio></control>' % (RIGHT - 640))
    x(3, '<control type="label"><left>%d</left><top>150</top><width>%d</width><height>136</height><font>povil_info_title</font>'
         '<textcolor>povil_white</textcolor><align>right</align><aligny>bottom</aligny>'
         '<label>$VAR[POVIL_I_Title]</label><visible>String.IsEmpty(ListItem.Art(povil_logo))</visible></control>' % (left - 100, COL + 100))
    x(3, '<control type="label"><left>%d</left><top>298</top><width>%d</width><height>40</height><font>povil_meta_bold</font>'
         '<textcolor>povil_gold</textcolor><align>right</align><aligny>center</aligny><label>$VAR[POVIL_I_Gold]</label></control>' % (left, COL))
    x(3, '<control type="grouplist"><left>%d</left><top>342</top><width>%d</width><height>42</height>'
         '<orientation>horizontal</orientation><align>right</align><itemgap>16</itemgap><usecontrolcoords>true</usecontrolcoords>' % (left, COL))
    x(4, '<control type="label"><width>auto</width><height>42</height><font>povil_meta</font><textcolor>povil_dim</textcolor><aligny>center</aligny><label>$VAR[POVIL_I_Meta]</label></control>')
    x(4, '<control type="label"><width>auto</width><height>42</height><font>povil_meta_bold</font><textcolor>povil_gold</textcolor><aligny>center</aligny>'
         '<label>$INFO[ListItem.Rating]$INFO[ListItem.Votes,  (,)]</label><visible>Integer.IsGreater(ListItem.Rating,0)</visible></control>')
    x(4, '<control type="image"><top>10</top><width>22</width><height>22</height><texture colordiffuse="povil_gold">povil/star.png</texture><visible>Integer.IsGreater(ListItem.Rating,0)</visible></control>')
    x(3, '</control>')
    x(3, '<control type="textbox" id="4"><left>%d</left><top>402</top><width>%d</width><height>264</height><font>povil_plot</font>'
         '<textcolor>povil_white</textcolor><align>right</align><autoscroll delay="7000" time="3000" repeat="10000">true</autoscroll>'
         '<label>$INFO[ListItem.Plot]</label></control>' % (left, COL))
    # Cast (Kodi shows it in place of the plot): photo on the right, name and role to its left
    x(3, '<control type="list" id="50"><left>%d</left><top>396</top><width>%d</width><height>280</height>' % (left, COL))
    x(4, '<orientation>vertical</orientation><scrolltime tween="cubic" easing="out">200</scrolltime><onup>9000</onup><ondown>9000</ondown>')
    for focused in (False, True):
        tag = 'focusedlayout' if focused else 'itemlayout'
        x(4, '<%s height="70" width="%d">' % (tag, COL))
        if focused:
            x(5, '<control type="image"><left>0</left><top>2</top><width>%d</width><height>66</height>'
                 '<texture border="30" colordiffuse="26FFFFFF">povil/rounded_fill.png</texture><visible>Control.HasFocus(50)</visible></control>' % COL)
        x(5, '<control type="image"><left>%d</left><top>7</top><width>56</width><height>56</height>'
             '<texture background="true" diffuse="povil/pill.png" fallback="DefaultActor.png">$INFO[ListItem.Art(thumb)]</texture>'
             '<aspectratio scalediffuse="false">scale</aspectratio></control>' % (COL - 66))
        x(5, '<control type="label"><left>%d</left><top>0</top><width>%d</width><height>70</height><font>povil_row</font>'
             '<textcolor>%s</textcolor><align>right</align><aligny>center</aligny>'
             '<label>$INFO[ListItem.Label][COLOR povil_faint]$INFO[ListItem.Label2,  •  ][/COLOR]</label></control>'
             % (16, COL - 100, 'povil_white' if focused else 'povil_dim'))
        x(4, '</%s>' % tag)
    x(3, '</control>')
    # Credits
    for i, (cond, label) in enumerate((('!String.IsEmpty(ListItem.Director)', '[COLOR povil_faint]בימוי:[/COLOR]  $INFO[ListItem.Director]'),
                                       ('!String.IsEmpty(ListItem.Studio)', '[COLOR povil_faint]הפקה:[/COLOR]  $INFO[ListItem.Studio]$INFO[ListItem.Country,  •  ]'))):
        x(3, '<control type="label"><left>%d</left><top>%d</top><width>%d</width><height>38</height><font>povil_meta</font>'
             '<textcolor>povil_dim</textcolor><align>right</align><aligny>center</aligny><label>%s</label>'
             '<visible>%s + !Control.IsVisible(50)</visible></control>' % (left, 690 + i * 42, COL, e(label), cond))
    # Buttons, Play rightmost
    x(3, '<control type="grouplist" id="9000"><left>%d</left><top>900</top><width>%d</width><height>64</height>' % (H.MARGIN, 1920 - 2 * H.MARGIN))
    x(4, '<orientation>horizontal</orientation><align>right</align><itemgap>18</itemgap>')
    x(4, '<onup condition="Control.IsVisible(50)">50</onup><ondown condition="Control.IsVisible(50)">50</ondown>')
    x(4, '<onup condition="!Control.IsVisible(50)">4</onup>')
    button(x, 5, 10, '$LOCALIZE[13511]', 'Control.IsEnabled(10) + !String.IsEmpty(ListItem.DBID)')
    button(x, 5, 6, '$LOCALIZE[184]', 'Control.IsEnabled(6)')
    button(x, 5, 11, 'קדימון', '!String.IsEmpty(ListItem.Trailer)')
    button(x, 5, 5, '', '!Integer.IsEqual(Container(50).NumItems,0)')
    button(x, 5, 8, '', '', primary=True,
           extra='<label>$VAR[POVIL_I_Play]</label>')
    x(3, '</control>')
    x(2, '</control>')
    x(1, '</controls>')
    x(0, '</window>')
    return x.text()


def variables():
    x = H.X()
    x(1, '<variable name="POVIL_I_Title">')
    x(2, '<value condition="%s">$INFO[ListItem.TVShowTitle]</value>' % IS_EP)
    x(2, '<value condition="!String.IsEmpty(ListItem.Title)">$INFO[ListItem.Title]</value>')
    x(2, '<value>$INFO[ListItem.Label]</value>')
    x(1, '</variable>')
    x(1, '<variable name="POVIL_I_Gold">')
    x(2, '<value condition="%s">$INFO[ListItem.Season,עונה , · ]$INFO[ListItem.Episode,פרק ]$INFO[ListItem.Title,  ·  ]</value>' % IS_EP)
    x(2, '<value condition="!String.IsEmpty(ListItem.Tagline)">$INFO[ListItem.Tagline]</value>')
    x(1, '</variable>')
    x(1, '<variable name="POVIL_I_Meta">')
    x(2, '<value condition="%s">$INFO[ListItem.Premiered]$INFO[ListItem.Duration(mins),  •  ,%s]</value>' % (IS_EP, MIN))
    x(2, '<value>$INFO[ListItem.Year]$INFO[ListItem.Genre,  •  ]$INFO[ListItem.Duration(mins),  •  ,%s]$INFO[ListItem.MPAA,  •  ]</value>' % MIN)
    x(1, '</variable>')
    x(1, '<variable name="POVIL_I_Play">')
    x(2, '<value condition="Container.Content(tvshows) | String.IsEqual(ListItem.DBType,tvshow)">$LOCALIZE[1024]</value>')
    x(2, '<value>$LOCALIZE[208]</value>')
    x(1, '</variable>')
    return x.text()


def main():
    folder = os.path.join(sys.argv[1], 'xml')
    with open(os.path.join(folder, 'DialogVideoInfo.xml'), 'w', encoding='utf-8', newline=NL) as f:
        f.write(gen())
    path = os.path.join(folder, 'Includes_POVIL_Home.xml')
    text = open(path, encoding='utf-8').read()
    begin, end = '<!-- POVIL INFO BEGIN -->', '<!-- POVIL INFO END -->'
    if begin in text:
        text = text[:text.index(begin)] + text[text.index(end) + len(end) + 1:]
    text = text.replace('</includes>', '\t' + begin + NL + variables() + '\t' + end + NL + '</includes>')
    with open(path, 'w', encoding='utf-8', newline=NL) as f:
        f.write(text)
    print('info screen generated')


if __name__ == '__main__':
    main()
