# -*- coding: utf-8 -*-
"""Generate the busy indicator and the notifications of skin.povil.onyx.

    python gen_dialogs.py ../../skin.povil.onyx

Busy: a thin gold arc turning in the middle of the screen, no dark curtain
over what is loading. Notifications: a floating card at the top centre, the
icon on the right and the heading in gold above the message (right to left).
"""
import os
import sys

from PIL import Image, ImageDraw

import gen_home as H

NL = chr(10)


def spinner(media):
    size, ss = 96, 4
    big = Image.new('L', (size * ss, size * ss), 0)
    d = ImageDraw.Draw(big)
    d.arc((6 * ss, 6 * ss, (size - 6) * ss, (size - 6) * ss), -90, 200, fill=255, width=5 * ss)
    mask = big.resize((size, size), Image.LANCZOS)
    img = Image.new('RGBA', (size, size), (255, 255, 255, 0))
    img.putalpha(mask)
    img.save(os.path.join(media, 'spinner.png'), optimize=True)
    ring = Image.new('L', (size * ss, size * ss), 0)
    ImageDraw.Draw(ring).ellipse((6 * ss, 6 * ss, (size - 6) * ss, (size - 6) * ss), outline=255, width=5 * ss)
    track = Image.new('RGBA', (size, size), (255, 255, 255, 0))
    track.putalpha(ring.resize((size, size), Image.LANCZOS))
    track.save(os.path.join(media, 'spinner_track.png'), optimize=True)


def busy():
    x = H.X()
    x(0, '<?xml version="1.0" encoding="UTF-8"?>')
    x(0, '<!-- Generated by tools/skin_onyx/gen_dialogs.py. Do not edit by hand. -->')
    x(0, '<window type="dialog">')
    x(1, '<animation effect="fade" time="260" delay="250">WindowOpen</animation>')
    x(1, '<animation effect="fade" time="120">WindowClose</animation>')
    x(1, '<controls>')
    x(2, '<control type="group">')
    x(3, '<left>912</left><top>492</top>')
    x(3, '<control type="image"><left>-36</left><top>-36</top><width>168</width><height>168</height>'
         '<texture colordiffuse="B3000000">povil/pill.png</texture></control>')
    x(3, '<control type="image"><left>0</left><top>0</top><width>96</width><height>96</height>'
         '<texture colordiffuse="26FFFFFF">povil/spinner_track.png</texture></control>')
    x(3, '<control type="image"><left>0</left><top>0</top><width>96</width><height>96</height>'
         '<texture colordiffuse="povil_gold">povil/spinner.png</texture>'
         '<animation effect="rotate" start="0" end="-360" center="48,48" time="900" loop="true" condition="true">Conditional</animation></control>')
    x(2, '</control>')
    x(1, '</controls>')
    x(0, '</window>')
    return x.text()


def notification():
    x = H.X()
    w, h = 860, 118
    left = (1920 - w) // 2
    x(0, '<?xml version="1.0" encoding="UTF-8"?>')
    x(0, '<!-- Generated by tools/skin_onyx/gen_dialogs.py. Do not edit by hand. -->')
    x(0, '<window type="dialog">')
    x(1, '<zorder>2</zorder>')
    x(1, '<animation type="WindowOpen"><effect type="fade" start="0" end="100" time="240" />'
         '<effect type="slide" start="0,-40" end="0,0" time="280" tween="cubic" easing="out" /></animation>')
    x(1, '<animation type="WindowClose"><effect type="fade" start="100" end="0" time="240" /></animation>')
    x(1, '<controls>')
    x(2, '<control type="group">')
    x(3, '<left>%d</left><top>36</top>' % left)
    x(3, '<control type="image"><left>-30</left><top>-22</top><width>%d</width><height>%d</height>'
         '<texture border="54">povil/shadow.png</texture></control>' % (w + 60, h + 60))
    x(3, '<control type="image"><left>0</left><top>0</top><width>%d</width><height>%d</height>'
         '<texture border="30" colordiffuse="F2141416">povil/rounded_fill.png</texture></control>' % (w, h))
    x(3, '<control type="image"><left>%d</left><top>%d</top><width>6</width><height>%d</height>'
         '<texture colordiffuse="povil_gold">povil/progress.png</texture></control>' % (w - 6, 24, h - 48))
    x(3, '<control type="image" id="400"><left>%d</left><top>19</top><width>80</width><height>80</height>'
         '<aspectratio>keep</aspectratio></control>' % (w - 108))
    x(3, '<control type="label" id="401"><left>28</left><top>14</top><width>%d</width><height>44</height>'
         '<font>povil_meta_bold</font><textcolor>povil_gold</textcolor><align>right</align><aligny>center</aligny></control>' % (w - 160))
    x(3, '<control type="label" id="402"><left>28</left><top>58</top><width>%d</width><height>44</height>'
         '<font>povil_meta</font><textcolor>povil_white</textcolor><align>right</align><aligny>center</aligny>'
         '<scroll>true</scroll></control>' % (w - 160))
    x(2, '</control>')
    x(1, '</controls>')
    x(0, '</window>')
    return x.text()


def main():
    skin = sys.argv[1]
    spinner(os.path.join(skin, 'media', 'povil'))
    with open(os.path.join(skin, 'xml', 'DialogBusy.xml'), 'w', encoding='utf-8', newline=NL) as f:
        f.write(busy())
    with open(os.path.join(skin, 'xml', 'DialogNotification.xml'), 'w', encoding='utf-8', newline=NL) as f:
        f.write(notification())
    print('busy + notification generated')


if __name__ == '__main__':
    main()
