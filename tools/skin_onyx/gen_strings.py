def quote(text):
    return text.replace(chr(92), chr(92) * 2).replace('"', chr(92) + '"')


def main():
    lang = os.path.join(sys.argv[1], 'language')
    src = open(os.path.join(lang, 'resource.language.en_gb', 'strings.po'), encoding='utf-8').read()
    entries = re.findall(r'msgctxt "#(\d+)"\s*\nmsgid "(.*)"', src)
    out = ['# Kodi Media Center language file', '# Addon Name: Kodi POV IL - Onyx', '# Addon id: skin.povil.onyx',
           'msgid ""', 'msgstr ""', '"Project-Id-Version: Kodi POV IL - Onyx' + chr(92) + 'n"',
           '"Content-Type: text/plain; charset=UTF-8' + chr(92) + 'n"', '"Content-Transfer-Encoding: 8bit' + chr(92) + 'n"',
           '"Language: he_IL' + chr(92) + 'n"', '"Plural-Forms: nplurals=2; plural=(n != 1);' + chr(92) + 'n"', '']
    done = 0
    for sid, english in entries:
        he = HE.get(int(sid))
        done += 1 if he else 0
        out += ['msgctxt "#%s"' % sid, 'msgid "%s"' % english, 'msgstr "%s"' % (quote(he) if he else ''), '']
    folder = os.path.join(lang, 'resource.language.he_il')
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, 'strings.po'), 'w', encoding='utf-8', newline=chr(10)) as f:
        f.write(chr(10).join(out))
    print('he_il strings: %d of %d translated' % (done, len(entries)))


if __name__ == '__main__':
    main()
