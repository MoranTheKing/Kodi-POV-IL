# -*- coding: utf-8 -*-
"""The settings screen's choices made in the skin itself, for a Kodi without the build's Wizard (Onyx 1.0.26).

    python gen_standalone.py ../../skin.povil.onyx

A viewer, via the owner, Nov 2026: Onyx installed on its own on his CoreELEC box (the build on his Shield) --
"the tile 'שורות משלי' is there after the update, but nothing happens when I press it", and no "send log". The
tiles ran the Wizard, which a Kodi with the skin alone does not have. The owner: the viewer who asked for the
rows is the one using them -- they must work there.

So, when the Wizard is not installed (gen_home.py SETTINGS_ITEMS, WIZ):
  * Custom_POVILRows.xml (window 1162) -- the viewer's own rows: a slot, then its source -- Kodi's library, one
    of the viewer's video sources (sources://video/, the disks and network shares Kodi already knows), or any
    folder through Kodi's own browser (Skin.SetPath) -- then its name; or the row deleted. The same skin strings
    the Wizard's custom_rows.py writes (POVILRow_<tab>_<n>_path / _name).
  * Custom_POVILChoice.xml (window 1161) -- which player (POVILPlayer, as onyx_player_style.py) or which screens
    the top bar shows (POVILHideTab_<tab>, as onyx_tabs.py), by Window(home).Property(povil.choice).
With the Wizard installed the tiles ask the Wizard, as before.
"""
import os
import sys

import gen_home as H

NL = chr(10)
CHOICE_ID, ROWS_ID = 1161, 1162
PLAYERS = (('', 'הנגן של Onyx (ברירת מחדל)'),) + tuple((v, 'נגן ' + n) for v, n in H.PLAYER_STYLES)
# (the screens the bar may drop: all but films and settings -- onyx_tabs.TABS)
SCREENS = (('tv', 'סדרות'), ('continue', 'המשך צפייה'), ('israeli', 'ישראלי'), ('live', 'שידור חי'),
           ('kids', 'ילדים'), ('favourites', 'מועדפים'), ('search', 'חיפוש'))
LIBRARY = (('videodb://movies/titles/', 'הספרייה של קודי: סרטים', 'סרטים מהספרייה'),
           ('videodb://tvshows/titles/', 'הספרייה של קודי: סדרות', 'סדרות מהספרייה'),
           ('videodb://recentlyaddedmovies/', 'הספרייה של קודי: סרטים שנוספו לאחרונה', 'נוספו לאחרונה'))
SLOT = 'Window(home).Property(povil.rows.slot)'
STEP = 'Window(home).Property(povil.rows.step)'
TAB_NAMES = dict(H.CUSTOM_TAB_NAMES)


def e(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')


def frame(x, wid, _unused=None):
    x(0, '<?xml version="1.0" encoding="UTF-8"?>')
    x(0, '<!-- Generated by tools/skin_onyx/gen_standalone.py. Do not edit by hand. -->')
    x(0, '<window type="dialog" id="%d">' % wid)


def panel(x, d, height=1010, width=760):
    x(d, '<control type="image">')
    x(d + 1, '<centerleft>960</centerleft><centertop>540</centertop><width>%d</width><height>%d</height>' % (width, height))
    x(d + 1, '<texture colordiffuse="$VAR[MenuTransperancy]" border="128">povil/panel.png</texture>')
    x(d, '</control>')


def heading(x, d, label, visible=None, top=70):
    x(d, '<control type="label">')
    x(d + 1, '<centerleft>960</centerleft><posy>%d</posy><width>690</width><height>52</height>' % top)
    x(d + 1, '<label>%s</label><align>center</align><aligny>center</aligny>' % e(label))
    x(d + 1, '<textcolor>$VAR[HighlightColor]</textcolor><include>TitleCommons</include>')
    if visible:
        x(d + 1, '<visible>%s</visible>' % visible)
    x(d, '</control>')


def note(x, d, label, visible=None, top=930):
    x(d, '<control type="textbox">')
    x(d + 1, '<centerleft>960</centerleft><posy>%d</posy><width>640</width><height>70</height>' % top)
    x(d + 1, '<font>size18</font><align>center</align><textcolor>$VAR[HighlightColor]</textcolor>')
    x(d + 1, '<label>%s</label>' % e(label))
    if visible:
        x(d + 1, '<visible>%s</visible>' % visible)
    x(d, '</control>')


def radio(x, d, cid, label, selected, clicks, visible=None):
    x(d, '<control type="radiobutton" id="%d">' % cid)
    if visible:
        x(d + 1, '<visible>%s</visible>' % visible)
    x(d + 1, '<width>640</width><height>66</height><font>size22</font>')
    # (right to left: the name on the right, the mark on the left)
    x(d + 1, '<label>%s</label><align>right</align><radioposx>24</radioposx>' % e(label))
    x(d + 1, '<focusedcolor>$VAR[FocusTextColor]</focusedcolor>')
    x(d + 1, '<texturefocus border="14" colordiffuse="$VAR[FocusBoxColor]">povil/focus_box.png</texturefocus>')
    for click in clicks:
        x(d + 1, '<onclick>%s</onclick>' % e(click))
    x(d + 1, '<selected>%s</selected>' % selected)
    x(d, '</control>')


def button(x, d, cid, label, clicks, visible=None, width=640):
    x(d, '<control type="button" id="%d">' % cid)
    x(d + 1, '<width>%d</width><height>66</height><font>size22</font>' % width)
    x(d + 1, '<label>%s</label><align>right</align><aligny>center</aligny><textoffsetx>24</textoffsetx>' % e(label))
    x(d + 1, '<focusedcolor>$VAR[FocusTextColor]</focusedcolor>')
    x(d + 1, '<texturefocus border="14" colordiffuse="$VAR[FocusBoxColor]">povil/focus_box.png</texturefocus>')
    x(d + 1, '<texturenofocus />')
    for click in clicks:
        if isinstance(click, tuple):
            x(d + 1, '<onclick condition="%s">%s</onclick>' % (click[0], e(click[1])))
        else:
            x(d + 1, '<onclick>%s</onclick>' % e(click))
    if visible:
        x(d + 1, '<visible>%s</visible>' % visible)
    x(d, '</control>')


def choice():
    """Window 1161: which player, or which screens on the bar."""
    x = H.X()
    frame(x, CHOICE_ID, None)
    mode = 'Window(home).Property(povil.choice)'
    x(1, '<defaultcontrol always="true">9000</defaultcontrol>')
    x(1, '<include>DialogOpenClose</include>')
    x(1, '<controls>')
    x(2, '<control type="group">')
    panel(x, 3, height=760)
    heading(x, 3, 'סוג נגן', 'String.IsEqual(%s,player)' % mode, top=200)
    heading(x, 3, 'המסכים בסרגל העליון', 'String.IsEqual(%s,tabs)' % mode, top=200)
    x(3, '<control type="grouplist" id="9000">')
    x(4, '<centerleft>960</centerleft><posy>270</posy><width>640</width><height>470</height>')
    x(4, '<onleft>noop</onleft><onright>noop</onright><onup>9000</onup><ondown>9000</ondown><itemgap>0</itemgap>')
    # (radiobuttons straight in the grouplist: the hidden ones are skipped when moving)
    for n, (value, name) in enumerate(PLAYERS):
        selected = ('String.IsEmpty(Skin.String(POVILPlayer))' if not value else
                    'String.IsEqual(Skin.String(POVILPlayer),%s)' % value)
        click = 'Skin.Reset(POVILPlayer)' if not value else 'Skin.SetString(POVILPlayer,%s)' % value
        radio(x, 4, 7710 + n, name, selected, [click, 'Dialog.Close(%d)' % CHOICE_ID], 'String.IsEqual(%s,player)' % mode)
    for n, (tab, name) in enumerate(SCREENS):
        radio(x, 4, 7730 + n, name, '!Skin.HasSetting(POVILHideTab_%s)' % tab, ['Skin.ToggleSetting(POVILHideTab_%s)' % tab],
              'String.IsEqual(%s,tabs)' % mode)
    x(3, '</control>')
    note(x, 3, 'סרטים והגדרות מוצגים תמיד.', 'String.IsEqual(%s,tabs)' % mode, top=760)
    x(2, '</control>')
    x(1, '</controls>')
    x(0, '</window>')
    return x.text()


def rows():
    """Window 1162: the viewer's own rows, without the Wizard."""
    x = H.X()
    frame(x, ROWS_ID, None)
    picking = 'String.IsEqual(%s,source)' % STEP
    x(1, '<defaultcontrol always="true">9000</defaultcontrol>')
    x(1, '<include>DialogOpenClose</include>')
    x(1, '<onload>ClearProperty(povil.rows.step,home)</onload>')
    x(1, '<onunload>ClearProperty(povil.rows.step,home)</onunload>')
    x(1, '<onunload>ClearProperty(povil.rows.slot,home)</onunload>')
    x(1, '<controls>')
    x(2, '<control type="group">')
    panel(x, 3)
    heading(x, 3, 'שורות משלי', '!' + picking)
    x(3, '<control type="label">')
    x(4, '<centerleft>960</centerleft><posy>70</posy><width>690</width><height>52</height>')
    x(4, '<label>$VAR[POVIL_RowPicking]</label><align>center</align><aligny>center</aligny>')
    x(4, '<textcolor>$VAR[HighlightColor]</textcolor><include>TitleCommons</include>')
    x(4, '<visible allowhiddenfocus="true">%s</visible>' % picking)
    x(3, '</control>')
    # --- the slots: every tab's rows, each with its name or "(ריקה)"
    x(3, '<control type="grouplist" id="9000">')
    x(4, '<centerleft>960</centerleft><posy>135</posy><width>640</width><height>792</height>')
    x(4, '<onleft>noop</onleft><onright>noop</onright><onup>9000</onup><ondown>9000</ondown><itemgap>0</itemgap>')
    x(4, '<visible allowhiddenfocus="true">!%s</visible>' % picking)
    cid = 7800
    for tab in H.CUSTOM_TABS:
        for n in range(1, H.CUSTOM_SLOTS + 1):
            button(x, 4, cid, '$VAR[POVIL_RowSlot_%s_%d]' % (tab, n),
                   ['SetProperty(povil.rows.slot,%s_%d,home)' % (tab, n), 'SetProperty(povil.rows.step,source,home)',
                    'SetFocus(9100)'])
            cid += 1
    x(3, '</control>')
    note(x, 3, 'שורה מופיעה בסוף המסך שלה, כשיש בה פריטים.', '!' + picking)
    # --- the source of the chosen slot
    key = 'POVILRow_$INFO[%s]' % SLOT
    then_name = 'Skin.SetString(%s_name)' % key          # Kodi's keyboard, with the name it has
    back = ['ClearProperty(povil.rows.step,home)', 'SetFocus(9000)']
    x(3, '<control type="grouplist" id="9100">')
    x(4, '<centerleft>960</centerleft><posy>135</posy><width>640</width><height>400</height>')
    x(4, '<onleft>noop</onleft><onright>noop</onright><onup>9200</onup><ondown>9200</ondown><itemgap>0</itemgap>')
    x(4, '<visible allowhiddenfocus="true">%s</visible>' % picking)
    for back_action in back:
        x(4, '<onback>%s</onback>' % back_action)
    for n, (path, label, name) in enumerate(LIBRARY):
        button(x, 4, 9110 + n, label, ['Skin.SetString(%s_path,%s)' % (key, path), 'Skin.SetString(%s_name,%s)' % (key, name),
                                       then_name] + back)
    button(x, 4, 9120, 'תיקייה אחרת (דפדוף)...', ['Skin.SetPath(%s_path)' % key, then_name] + back)
    button(x, 4, 9121, 'מחיקת השורה', ['Skin.Reset(%s_path)' % key, 'Skin.Reset(%s_name)' % key] + back)
    x(3, '</control>')
    # the viewer's own video sources, as Kodi lists them (a disk, a network share)
    x(3, '<control type="label"><centerleft>960</centerleft><posy>545</posy><width>640</width><height>44</height>'
         '<font>size18</font><align>right</align><textcolor>$VAR[HighlightColor]</textcolor>'
         '<label>מקורות הווידאו שלכם</label><visible>%s</visible></control>' % picking)
    x(3, '<control type="list" id="9200">')
    x(4, '<centerleft>960</centerleft><posy>590</posy><width>640</width><height>330</height>')
    x(4, '<onup>9100</onup><ondown>9100</ondown><onleft>noop</onleft><onright>noop</onright>')
    x(4, '<orientation>vertical</orientation><scrolltime>200</scrolltime>')
    x(4, '<visible allowhiddenfocus="true">%s</visible>' % picking)
    for back_action in back:
        x(4, '<onback>%s</onback>' % back_action)
    # ($ESCINFO: quoted, so a comma in a source's name or path cannot split the command -- the reviewer, 1.0.26)
    for click in ['Skin.SetString(%s_path,$ESCINFO[ListItem.FolderPath])' % key,
                  'Skin.SetString(%s_name,$ESCINFO[ListItem.Label])' % key, then_name] + back:
        x(4, '<onclick>%s</onclick>' % e(click))
    for layout, focused in (('itemlayout', False), ('focusedlayout', True)):
        x(4, '<%s height="66" width="640">' % layout)
        if focused:
            x(5, '<control type="image"><width>640</width><height>66</height>'
                 '<texture border="14" colordiffuse="$VAR[FocusBoxColor]">povil/focus_box.png</texture>'
                 '<visible>Control.HasFocus(9200)</visible></control>')
        x(5, '<control type="label"><left>24</left><width>592</width><height>66</height><font>size22</font>'
             '<align>right</align><aligny>center</aligny><textcolor>%s</textcolor><label>$INFO[ListItem.Label]</label></control>'
             % ('$VAR[FocusTextColor]' if focused else 'white'))
        x(4, '</%s>' % layout)
    x(4, '<content>sources://video/</content>')
    x(3, '</control>')
    x(2, '</control>')
    x(1, '</controls>')
    x(0, '</window>')
    return x.text()


def variables():
    """The slot names the dialog shows, and the name a row has when the viewer gave none."""
    x = H.X()
    x(1, '<!-- POVIL STANDALONE BEGIN: generated by tools/skin_onyx/gen_standalone.py -->')
    for tab in H.CUSTOM_TABS:
        for n in range(1, H.CUSTOM_SLOTS + 1):
            key = 'POVILRow_%s_%d' % (tab, n)
            x(1, '<variable name="POVIL_RowSlot_%s_%d">' % (tab, n))
            x(2, '<value condition="String.IsEmpty(Skin.String(%s_path))">%s · שורה %d: (ריקה)</value>' % (key, TAB_NAMES[tab], n))
            x(2, '<value condition="!String.IsEmpty(Skin.String(%s_name))">%s · שורה %d: $INFO[Skin.String(%s_name)]</value>'
              % (key, TAB_NAMES[tab], n, key))
            x(2, '<value>%s · שורה %d: השורה שלי</value>' % (TAB_NAMES[tab], n))
            x(1, '</variable>')
    x(1, '<variable name="POVIL_RowPicking">')
    for tab in H.CUSTOM_TABS:
        for n in range(1, H.CUSTOM_SLOTS + 1):
            x(2, '<value condition="String.IsEqual(%s,%s_%d)">מקור לשורה: %s · שורה %d</value>' % (SLOT, tab, n, TAB_NAMES[tab], n))
    x(2, '<value>מקור לשורה</value>')
    x(1, '</variable>')
    x(1, '<!-- POVIL STANDALONE END -->')
    return x.text()


def main():
    folder = os.path.join(sys.argv[1], 'xml')
    for name, text in (('Custom_POVILChoice.xml', choice()), ('Custom_POVILRows.xml', rows())):
        with open(os.path.join(folder, name), 'w', encoding='utf-8', newline=NL) as f:
            f.write(text)
    path = os.path.join(folder, 'Includes_POVIL_Home.xml')
    text = open(path, encoding='utf-8').read()
    begin, end = '<!-- POVIL STANDALONE BEGIN', '<!-- POVIL STANDALONE END -->'
    if begin in text:
        start = text.rindex(NL, 0, text.index(begin)) + 1
        stop = text.index(NL, text.index(end)) + 1
        text = text[:start] + text[stop:]
    text = text.replace('</includes>', variables() + '</includes>', 1)
    with open(path, 'w', encoding='utf-8', newline=NL) as f:
        f.write(text)
    print('standalone dialogs generated: %d, %d' % (CHOICE_ID, ROWS_ID))


if __name__ == '__main__':
    main()
