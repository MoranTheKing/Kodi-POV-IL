def e(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')


def frame(x, wid, _unused=None):
    x(0, '<?xml version="1.0" encoding="UTF-8"?>')
    x(0, '<!-- Generated by tools/skin_onyx/gen_standalone.py. Do not edit by hand. -->')
    x(0, '<window type="dialog" id="%d">' % wid)


