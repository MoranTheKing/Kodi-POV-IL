    heading(x, 3, 'סוג נגן', 'String.IsEqual(%s,player)' % mode, top=200)
    heading(x, 3, 'המסכים בסרגל העליון', 'String.IsEqual(%s,tabs)' % mode, top=200)
    x(3, '<control type="grouplist" id="9000">')
    x(4, '<centerleft>960</centerleft><posy>270</posy><width>640</width><height>470</height>')
    x(4, '<onleft>noop</onleft><onright>noop</onright><onup>9000</onup><ondown>9000</ondown><itemgap>0</itemgap>')
    # (radiobuttons straight in the grouplist: the hidden ones are skipped when moving)
