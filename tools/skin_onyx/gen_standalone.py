def radio(x, d, cid, label, selected, clicks, visible=None):
    x(d, '<control type="radiobutton" id="%d">' % cid)
    if visible:
        x(d + 1, '<visible>%s</visible>' % visible)
    x(d + 1, '<width>640</width><height>66</height><font>size22</font>')
    # (right to left: the name on the right, the mark on the left)
    x(d + 1, '<label>%s</label><align>right</align><radioposx>24</radioposx>' % e(label))
    x(d + 1, '<focusedcolor>$VAR[FocusTextColor]</focusedcolor>')
    x(d + 1, '<texturefocus border="14" colordiffuse="$VAR[FocusBoxColor]">povil/focus_box.png</texturefocus>')
    for click in clicks:
        x(d + 1, '<onclick>%s</onclick>' % e(click))
    x(d + 1, '<selected>%s</selected>' % selected)
    x(d, '</control>')


def button(x, d, cid, label, clicks, visible=None, width=640):
    x(d, '<control type="button" id="%d">' % cid)
    x(d + 1, '<width>%d</width><height>66</height><font>size22</font>' % width)
    x(d + 1, '<label>%s</label><align>right</align><aligny>center</aligny><textoffsetx>24</textoffsetx>' % e(label))
